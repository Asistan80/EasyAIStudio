"use strict";

/* ==========================================================
   API Key Manager
   ========================================================== */

const APIKeyManager = {

    storageKey: "api-keys",

    keys: {},

    /* ======================================================
       Initialize
       ====================================================== */

    init() {

        this.load();

        console.log(

            "API Key Manager Ready"

        );

    },

    /* ======================================================
       Load
       ====================================================== */

    load() {

        this.keys = Storage.get(

            this.storageKey,

            {}

        );

    },

    /* ======================================================
       Save
       ====================================================== */

    save() {

        Storage.set(

            this.storageKey,

            this.keys

        );

    },

    /* ======================================================
       Set Key
       ====================================================== */

    set(provider, key) {

        this.keys[provider] = {

            value: key,

            updated: Utils.now()

        };

        this.save();

        EventBus.emit(

            "apikey.updated",

            provider

        );

    },

    /* ======================================================
       Get Key
       ====================================================== */

    get(provider) {

        return this.keys[provider]

            ? this.keys[provider].value

            : "";

    },

    /* ======================================================
       Has Key
       ====================================================== */

    has(provider) {

        return Boolean(

            this.get(provider)

        );

    },

    /* ======================================================
       Remove Key
       ====================================================== */

    remove(provider) {

        delete this.keys[provider];

        this.save();

        EventBus.emit(

            "apikey.removed",

            provider

        );

    },

    /* ======================================================
       Clear All
       ====================================================== */

    clear() {

        this.keys = {};

        this.save();

    },

    /* ======================================================
       Providers
       ====================================================== */

    providers() {

        return Object.keys(

            this.keys

        );

    }

};

/* ==========================================================
   Global
   ========================================================== */

window.APIKeyManager = APIKeyManager;