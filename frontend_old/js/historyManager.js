"use strict";



/* ==========================================================
   History Manager
   ========================================================== */

const HistoryManager = {



    items: [],





    /* ======================================================
       Initialize
       ====================================================== */

    init() {


        this.load();



        console.log(

            "History Manager Ready"

        );


    },







    /* ======================================================
       Add Record
       ====================================================== */

    add(type, data) {



        const record = {



            id:

                Utils.uuid(),



            type:

                type,



            data:

                data,



            date:

                new Date()



        };





        this.items.unshift(

            record

        );





        this.save();



        EventBus.emit(

            "history.added",

            record

        );



        return record;



    },







    /* ======================================================
       Get All
       ====================================================== */

    all() {


        return this.items;


    },







    /* ======================================================
       Filter
       ====================================================== */

    get(type) {



        return this.items.filter(

            item =>

            item.type === type

        );



    },







    /* ======================================================
       Remove
       ====================================================== */

    remove(id) {



        this.items =

            this.items.filter(

                item =>

                item.id !== id

            );



        this.save();



    },







    /* ======================================================
       Clear
       ====================================================== */

    clear() {



        this.items = [];



        this.save();



    },







    /* ======================================================
       Load
       ====================================================== */

    load() {



        this.items =

            Storage.get(

                "history",

                []

            );



    },







    /* ======================================================
       Save
       ====================================================== */

    save() {



        Storage.set(

            "history",

            this.items

        );



    }



};







/* ==========================================================
   Global
   ========================================================== */

window.HistoryManager = HistoryManager;